import type { Metadata } from "next";
import { GeistSans } from "geist/font/sans";
import { GeistMono } from "geist/font/mono";
import { LazyMotion, domAnimation } from "framer-motion";
import { Analytics } from "@vercel/analytics/next";
import { PageCurtain } from "./components/page-curtain";
import { siteUrl } from "./site-url";
import "./globals.css";

// Both fonts come from the geist package (local woff2, no network request).
// Each exposes a CSS variable applied via className on <html>:
//
//   GeistSans → --font-geist-sans → body AND display text (per Instruction.md)
//   GeistMono → --font-geist-mono → monospaced / labels
//
// Note: the refined token system uses Geist for display headings — there is no
// separate pixel display font in this system.

const title = "Maryna Babych — Lead Product Designer";
const description =
  "Portfolio of Maryna Babych, Lead Product Designer based in Auckland, New Zealand. 9 years crafting award-winning digital experiences.";

/*
  metadataBase is what lets Next resolve the relative OG image URL. Without it
  the tag is silently dropped, which is what left a shared link rendering as a
  blank card.
*/
export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title,
  description,
  alternates: { canonical: "/" },
  // The OG image itself is generated by app/opengraph-image.tsx; Next wires it
  // into both cards automatically, so neither block names an image.
  openGraph: {
    type: "website",
    siteName: "Maryna Babych",
    locale: "en_NZ",
    url: "/",
    title,
    description,
  },
  twitter: { card: "summary_large_image", title, description },
};

// Theme is resolved entirely on the client, before first paint, by the inline
// script below. It used to be read from a cookie here on the server — which
// worked, but reading cookies() in the ROOT layout opts every route in the app
// out of static generation, so all seven pages were server-rendered on demand
// and none could be cached at the edge. A portfolio that changes a few times a
// year should be static HTML.
//
// Nothing is lost visually: a visitor with no saved preference gets no
// data-theme attribute at all and the prefers-color-scheme media query in
// globals.css picks the right palette, exactly as before; a visitor who HAS
// chosen gets data-theme stamped by the blocking script before anything
// paints. The one thing the server can no longer know is which glyph the
// theme toggle should start on, so it renders the light-mode icon and
// useSyncExternalStore corrects it on hydration — the same path first-time
// visitors have always taken.
export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={[
        GeistSans.variable,
        GeistMono.variable,
        "h-full antialiased",
      ].join(" ")}
      suppressHydrationWarning
    >
      <head>
        {/*
          Applies a SAVED theme before first paint, so a visitor who chose light
          on a dark OS (or the reverse) never sees the wrong palette flash.
          Deliberately does nothing when no choice is saved: leaving data-theme
          off lets the prefers-color-scheme rules in globals.css resolve the
          default, which is already flash-free.

          A RAW <script>, not next/script. `strategy="beforeInteractive"` does
          not inline anything — it pushes the source onto a queue that Next's
          runtime drains once the framework chunk has loaded, which is after the
          first paint. That was invisible while the server stamped data-theme
          from a cookie; with the cookie gone this script is the only thing
          standing between a saved-preference visitor and a flash of the wrong
          theme, so it has to execute during HTML parse.
        */}
        <script
          dangerouslySetInnerHTML={{
            __html:
              "(function(){try{var t=localStorage.getItem('theme');if(t==='dark'||t==='light'){document.documentElement.setAttribute('data-theme',t);}}catch(e){}})();",
          }}
        />
      </head>
      <body className="min-h-full flex flex-col">
        {/* domAnimation covers everything the site uses (hover/tap/animate/
            AnimatePresence) without drag/layout — smaller than importing the
            full `motion` feature set on every page. `m.*` components below
            read features from this provider instead of bundling their own. */}
        <LazyMotion features={domAnimation} strict>
          {children}
          {/* Route transition: sweeps up over the outgoing page, swaps, sweeps off. */}
          <PageCurtain />
        </LazyMotion>
        <Analytics />
      </body>
    </html>
  );
}
